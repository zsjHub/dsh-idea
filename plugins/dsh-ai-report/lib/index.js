/** AI 数据叙事分析插件：注册 build-ai-report Skill 为系统提示段。 */
const name = 'dsh-ai-report';
const inject = ['systemPrompt'];

function apply(ctx) {
  ctx.systemPrompt.section({
    name: 'skill:build-ai-report',
    order: 100,
    text: [
      '## 构建 AI 数据叙事报告',
      '',
      '把 Excel 转换成读者能快速理解的离线交互报告。目标不是复刻表格，而是从数据问题出发，形成"可信口径 → 明确结论 → 合适图表 → 可核验成果"的闭环。',
      '',
      '## 硬边界',
      '',
      '- 只读打开源工作簿；不得覆盖、另存、重算或重新格式化源文件。',
      '- 生成前后记录源文件的 SHA-256、大小和修改时间，确认源文件没有变化。',
      '- 不编造缺失值、分类、单位、时间、来源或业务含义；推断必须明确标记。',
      '- 不把公式文本当作结果。公式缓存为空、过期或无法验证时，报告限制并停止使用该指标。',
      '- HTML 只嵌入绘图所需的聚合数据，不嵌入完整明细，不提供原始数据下载入口。',
      '- 使用 openpyxl 只读解析 Excel，并执行显式聚合。',
      '- 使用 Apache ECharts 6.1.0 渲染，并将运行时内联。',
      '- 最终成果无需服务器和 CDN，双击即可打开。',
      '',
      '## 阶段 1：锁定输入和只读基线',
      '',
      '1. 使用 DSH 文件工具读取用户指定的 Excel 路径，确认文件存在、可读，扩展名为 .xlsx 或 .xlsm。',
      '2. 记录文件大小、修改时间和 SHA-256。',
      '3. 使用只读模式打开工作簿。',
      '',
      '## 阶段 2：剖析工作簿',
      '',
      '至少确认：',
      '- 工作表名称、可见性、有效区域、候选表头、数据行列数',
      '- 合并单元格、空白行列、重复表头、筛选区域、Excel Table 和命名区域',
      '- 每列的推断类型、非空数、缺失率、唯一值数、最小/最大值、时间范围和单位线索',
      '- 公式单元格、公式缓存、日期序列、百分比、货币和千分位显示格式',
      '- 可能的 ID、维度、度量、时间、层级、分类和备注字段',
      '',
      '不要默认第一行是表头，也不要默认最大工作表就是目标数据。',
      '',
      '## 阶段 3：建立分析口径',
      '',
      '先写清楚问题，再计算数据。对每个结论记录以下五项：',
      '- 问题：这张图具体回答什么',
      '- 字段：使用哪些维度、度量、时间和 ID',
      '- 筛选：纳入和排除哪些记录',
      '- 计算：聚合函数、分母、去重键、单位换算',
      '- 校验：能回算到工作簿的总数、占比或边界',
      '',
      '## 阶段 4：选择图表和叙事顺序',
      '',
      '按分析问题 + 数据形状 + 阅读任务选择图表：',
      '',
      '- 随时间如何变化 → 折线图',
      '- 谁高谁低 → 排序横向条形图',
      '- 整体由什么构成 → 100% 堆叠条、环形图',
      '- 多组构成如何不同 → 100% 堆叠条形图',
      '- 前后发生多少变化 → 坡度图、哑铃图',
      '- 数据如何分布 → 直方图、箱线图',
      '- 两个数值是否相关 → 散点图',
      '- 两个维度如何交叉 → 热力图、气泡矩阵',
      '',
      '标题写结论，副标题写口径。多图报告按总览 → 变化 → 构成/排名 → 关系/原因 → 结论组织。',
      '',
      '## 阶段 5：生成离线报告',
      '',
      '使用 Python 脚本构建报告：',
      '1. 使用 openpyxl 只读解析 Excel，并执行显式聚合',
      '2. 校验工作簿 SHA-256、记录数、字段数和关键分类加总',
      '3. 只向 HTML 写入聚合数据',
      '4. 使用 Apache ECharts 6.1.0 渲染，并将运行时内联',
      '5. 使用一套统一的颜色体系，颜色承担稳定语义',
      '6. 标题先表达结论，副标题再说明口径，来源行标明数据来源',
      '',
      '构建脚本示例：',
      '```',
      'python3 generated/<工作簿名>/scripts/build_report.py --input <用户工作簿路径> --output generated/<工作簿名>/output/index.html',
      '```',
      '',
      '## 阶段 6：数据对账和浏览器验收',
      '',
      '1. 页面总数、均值、占比、排名、Top N、时间范围和标注值能回算到源 Excel',
      '2. 百分比分母和舍入正确',
      '3. HTML 不含远程脚本、在线字体、完整原始表或数据下载链接',
      '4. 页面没有控制台错误和远程资源请求',
      '5. 桌面端和移动端均无横向溢出、裁切、标签碰撞',
      '6. 交互控件真实改变图表',
      '7. 再次核对源工作簿 SHA-256、大小和修改时间未改变',
      '',
      '## 失败时如何处理',
      '',
      '- 找不到工作表或字段：停止构建，列出实际发现的工作表/列和预期项',
      '- 哈希或行列基线变化：先重新剖析并解释变化',
      '- 公式无缓存：不使用该指标，说明需要由 Excel 或兼容计算引擎重算',
      '- 分类加总不一致：定位缺失类、重复类、筛选条件和分母',
      '',
      '## 最终回复',
      '',
      '用中文简洁报告：',
      '- 输入工作表/区域、有效记录数和排除记录数',
      '- 采用的分析问题、核心结论和图表类型',
      '- 构建后的 HTML 与预览图路径',
      '- 数据对账、离线打开、桌面端、移动端、交互和源文件未修改是否通过',
      '- 任何未验证项、公式限制或数据口径风险',
    ].join('\n'),
  });
}

export { name, inject, apply };